#!/usr/bin/env python3
"""Run after generating Treasure decay to pack each layout into one scoreboard value."""
import re
from itertools import groupby
from math import prod
from pathlib import Path

ROTATIONS = (0, 90, 180, 270)
CALL = "function lbp_ext:decay/lower/"
LAYOUT = "#decay_layout lbp_info"
CHOICE = "#decay_choice lbp_info"
DISPATCH = re.compile(r"(execute .+) (if score .+ run) function lbp_ext:decay/lower/(\d+)/rot_\d+")


def compact(files):
    layouts = [
        [[line for line in files[f"lower/{i}/rot_{r}"] if line.startswith("function ")] for i in range(100)]
        for r in ROTATIONS
    ]
    choices = [list(dict.fromkeys(slot)) for slot in zip(*layouts[0])]
    radices = [len(slot) for slot in choices]
    assert all(len(row) == len(choices) for rows in layouts for row in rows)
    assert prod(radices) <= 2**31

    packed = []
    for row in layouts[0]:
        value = 0
        for cmd, slot in reversed(list(zip(row, choices))):
            value = value * len(slot) + slot.index(cmd)
        packed.append(value)

    routes = [m.groups() for line in files["lower/rot_0"] if (m := DISPATCH.fullmatch(line))]
    select = [f"scoreboard players set {LAYOUT} -1"]
    extra = {}
    for i, (condition, rows) in enumerate(groupby(routes, key=lambda row: row[0])):
        table = f"select/{i}"
        select.append(f"{condition} run {CALL}{table}")
        extra[f"lower/{table}"] = [
            f"execute {roll} scoreboard players set {LAYOUT} {packed[int(layout)]}"
            for _, roll, layout in rows
        ]
    extra["lower/select"] = select

    last = max(i for i, radix in enumerate(radices) if radix > 1)
    for r, rows in zip(ROTATIONS, layouts):
        key = f"lower/rot_{r}"
        body = files[key]
        indexes = [i for i, line in enumerate(body) if DISPATCH.fullmatch(line)]
        assert [DISPATCH.fullmatch(body[i]).groups() for i in indexes] == routes
        assert indexes == list(range(indexes[0], indexes[-1] + 1))
        files[key] = body[:indexes[0]] + [
            f"{CALL}select",
            f"execute if score {LAYOUT} matches 0.. run {CALL}apply/rot_{r}",
        ] + body[indexes[-1] + 1:]

        decode = [
            f"scoreboard players set #decay_base_{n} lbp_info {n}"
            for n in sorted(set(radices) - {1})
        ]
        for i, (slot, radix) in enumerate(zip(choices, radices)):
            by_rotation = {row0[i]: row[i] for row0, row in zip(layouts[0], rows)}
            assert all(by_rotation[row0[i]] == row[i] for row0, row in zip(layouts[0], rows))
            if radix == 1:
                decode.append(by_rotation[slot[0]])
                continue
            holder = LAYOUT
            if i != last:
                holder = CHOICE
                base = f"#decay_base_{radix} lbp_info"
                decode += [f"scoreboard players operation {CHOICE} = {LAYOUT}",
                           f"scoreboard players operation {CHOICE} %= {base}",
                           f"scoreboard players operation {LAYOUT} /= {base}"]
            decode += [
                f"execute if score {holder} matches {j} run {by_rotation[cmd]}"
                for j, cmd in enumerate(slot)
            ]
        extra[f"lower/apply/rot_{r}"] = decode

    for r in ROTATIONS:
        for i in range(100):
            del files[f"lower/{i}/rot_{r}"]
    files.update(extra)


def main():
    root = Path(__file__).resolve().parents[1] / "lbp_extensions/data/lbp_ext/functions/decay"
    paths = {p.relative_to(root).with_suffix("").as_posix(): p for p in (root / "lower").rglob("*.mcfunction")}
    files = {name: p.read_text(encoding="utf-8").splitlines() for name, p in paths.items()}
    header = "# generated by tools/compact_treasure_layouts.py"
    compact(files)
    for name, lines in files.items():
        path = root / (name + ".mcfunction")
        path.parent.mkdir(parents=True, exist_ok=True)
        if not lines[0].startswith("#"):
            lines = [header, ""] + lines
        path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    for name in paths.keys() - files.keys():
        paths[name].unlink()


if __name__ == "__main__":
    main()
